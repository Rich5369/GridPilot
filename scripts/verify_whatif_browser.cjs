// Local frontend :5173 and genuine optimizer :8000. No AI credentials required.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = [], submissions = [], responses = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', r => { if (r.url().endsWith('/api/optimize')) submissions.push(r.postDataJSON()) })
    page.on('response', async r => { if (r.url().endsWith('/api/optimize') && r.status() === 200) responses.push(await r.json()) })
    await page.goto('http://127.0.0.1:5173')
    const click = name => page.getByRole('button', { name, exact: true }).click()
    const nav = name => page.getByRole('navigation').getByRole('button', { name, exact: true }).click()
    await nav('What-if scenarios')
    await click('Create alternative from current')
    await page.locator('#alternative-limit').fill('15')
    await page.locator('#alternative-evEnergy').fill('18')
    await page.locator('#alternative-deadline').fill('18')
    await page.locator('#alternative-peak').fill('0.4')
    await click('Compare both scenarios')
    await page.getByText('Constraint satisfaction: Feasible — reported by backend', { exact: true }).nth(1).waitFor()
    assert.equal(submissions.length, 2)
    assert.equal(submissions[0].building_max_demand_kw, 25)
    assert.equal(submissions[1].building_max_demand_kw, 15)
    assert.equal(submissions[1].ev_requirements[0].energy_required_kwh, 18)
    assert.equal(submissions[1].ev_requirements[0].deadline_hour, 18)
    assert.equal(submissions[1].electricity_prices_usd_per_kwh[14], 0.4)
    for (let i=0; i<2; i++) {
      const article = page.locator('.what-if-grid article').nth(i)
      assert((await article.innerText()).includes(new Intl.NumberFormat('en-US',{ style:'currency',currency:'USD' }).format(responses[i].optimized_electricity_cost_usd)))
    }
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow')
    await page.screenshot({ path: '/tmp/gridpilot-phase6-mobile.png', fullPage: true })
    await page.locator('#alternative-limit').fill('1')
    await page.getByText('Inputs changed. Outdated comparison results are hidden; compare again.').waitFor()
    assert.equal(await page.locator('.what-if-grid article').count(), 0)
    await click('Compare both scenarios')
    await page.getByText('Constraint satisfaction: Infeasible — reported by backend', { exact: true }).waitFor()
    const infeasible = page.locator('.what-if-grid article').nth(1)
    assert((await infeasible.innerText()).includes('Unavailable'))
    assert((await infeasible.innerText()).includes(responses[3].constraint_violations[0]))
    await click('Apply alternative to current')
    await nav('Scenario configuration')
    assert.equal(await page.locator('#limit').inputValue(), '1')
    await nav('What-if scenarios')
    await click('Restore starting scenario')
    await nav('Scenario configuration')
    assert.equal(await page.locator('#limit').inputValue(), '25')
    await nav('What-if scenarios')
    await page.locator('#alternative-deadline').fill('3')
    assert(await page.getByRole('button', { name: 'Compare both scenarios', exact: true }).isDisabled())
    await page.locator('#alternative-deadline').fill('18')
    let active = 0, maxActive = 0
    await page.route('**/api/optimize', async route => {
      active++; maxActive = Math.max(maxActive, active)
      await new Promise(resolve => setTimeout(resolve, 200))
      active--
      await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: { code: 'solver_unavailable' } }) })
    })
    await click('Compare both scenarios')
    assert(await page.getByRole('button', { name: 'Compare both scenarios', exact: true }).isDisabled())
    await page.getByText('The optimization solver is unavailable or could not finish', { exact: false }).nth(1).waitFor()
    assert.equal(maxActive, 1)
    assert.equal(await page.locator('.what-if-grid article .comparison').count(), 0)
    assert.deepEqual(errors, [])
    console.log('PASS: genuine feasible pair, exact request configurations and returned costs, infeasible reasons/null values, stale invalidation, apply/restore, validation, sequential requests/loading/503, mobile overflow, no browser errors.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
