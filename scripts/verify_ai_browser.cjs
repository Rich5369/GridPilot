// Optional Playwright QA. Backend :8000 live without key, :8001 MODEL_API_MODE=mock;
// frontend :5173. Provider output is a mock fixture; optimizer calls are real.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const { isEvOnlyOptimization } = require('./browser-api.cjs')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    const nav = name => page.getByRole('navigation').getByRole('button', { name, exact: true }).click()
    await page.goto('http://127.0.0.1:5173')
    // Deterministic unavailable response: never invoke live Meta inference.
    await page.route('**/api/ai/**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: { message: 'Meta AI is unavailable: injected for browser verification' } }) }))
    // Mount an earlier manual session before a later AI handoff.
    await nav('What-if scenarios')
    await page.getByRole('button', { name: 'Create alternative from current', exact: true }).click()
    await nav('AI assistant')
    await page.getByRole('button', { name: 'Keep peak power demand below 15 kW.', exact: true }).click()
    await page.getByRole('button', { name: 'Review proposed changes', exact: true }).click()
    await page.getByText('Meta AI is unavailable:', { exact: false }).waitFor()
    // Forward browser requests to the explicit mock-mode backend.
    await page.route('**/api/ai/**', async route => {
      const response = await route.fetch({ url: route.request().url().replace(':8000', ':8001') })
      await route.fulfill({ response })
    })
    await page.getByRole('button', { name: 'Review proposed changes', exact: true }).click()
    await page.getByText('MOCK MODE — NOT META AI', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await nav('Scenario configuration')
    assert.equal(await page.locator('#limit').inputValue(), '25')
    await nav('AI assistant')
    await page.getByRole('button', { name: 'Keep peak power demand below 15 kW.', exact: true }).click()
    await page.getByRole('button', { name: 'Review proposed changes', exact: true }).click()
    await page.getByRole('button', { name: 'Apply Changes', exact: true }).click()
    await nav('Scenario configuration')
    assert.equal(await page.locator('#limit').inputValue(), '15')
    const resultPromise = page.waitForResponse(r => isEvOnlyOptimization(r))
    await page.getByRole('button', { name: 'Run optimization', exact: true }).click()
    const result = await resultPromise
    assert.equal(result.status(), 200)
    assert.equal((await result.json()).feasibility_status, 'feasible')
    await nav('AI assistant')
    await page.getByRole('button', { name: 'Explain latest backend result', exact: true }).click()
    await page.getByText('Mock selection — not Meta AI', { exact: true }).waitFor()
    await page.getByText('The modeled scenario is feasible.', { exact: true }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow')
    await page.screenshot({ path: '/tmp/gridpilot-phase5-mobile.png', fullPage: true })
    await nav('Scenario configuration')
    await page.locator('#limit').fill('20')
    await nav('AI assistant')
    await page.getByRole('button', { name: 'Keep peak power demand below 15 kW.', exact: true }).click()
    await page.getByRole('button', { name: 'Review proposed changes', exact: true }).click()
    await page.getByRole('button', { name: 'Compare as alternative', exact: true }).click()
    assert.equal(await page.locator('#alternative-limit').inputValue(), '15')
    await nav('Scenario configuration')
    assert.equal(await page.locator('#limit').inputValue(), '20')
    await nav('What-if scenarios')
    await page.getByRole('button', { name: 'Compare both scenarios', exact: true }).click()
    await page.getByText('Constraint satisfaction: Feasible — reported by backend', { exact: true }).nth(1).waitFor()
    await page.getByRole('button', { name: 'Apply alternative to current', exact: true }).click()
    await nav('Scenario configuration')
    assert.equal(await page.locator('#limit').inputValue(), '15')
    await nav('What-if scenarios')
    await page.getByRole('button', { name: 'Restore starting scenario', exact: true }).click()
    await nav('Scenario configuration')
    assert.equal(await page.locator('#limit').inputValue(), '20')
    assert.equal(await page.locator('#scheduling-mode').inputValue(), 'ev_only')
    assert.deepEqual(errors, [])
    console.log('PASS: injected AI-unavailable response, mock review/cancel/apply and mounted What-if handoff/restore, real optimizer, grounded explanation, mobile overflow, no browser errors. Live Meta API NOT tested.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
