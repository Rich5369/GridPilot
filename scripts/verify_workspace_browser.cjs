// Real local backend and frontend. Only failure responses below are injected.
// NODE_PATH=/tmp/gridpilot-browser/node_modules node scripts/verify_workspace_browser.cjs
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const { assertChartRendered } = require('./chart-rendering.cjs')
const { isEvOnlyOptimization, isJointOptimization } = require('./browser-api.cjs')
const output = process.env.GRIDPILOT_QA_OUTPUT || 'artifacts/scenario-workspace'
;(async () => {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch()
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
    const errors = [], records = []
    page.on('pageerror', e => errors.push(e.message))
    const nav = name => page.getByRole('navigation').getByRole('button', { name, exact: true }).click()
    const click = name => page.getByRole('button', { name, exact: true }).click()
    const run = async (predicate = isEvOnlyOptimization) => {
      const response = page.waitForResponse(predicate)
      await click('Run optimization')
      const r = await response, result = await r.json()
      assert.equal(r.status(), 200)
      records.push({ scenario: r.request().postDataJSON(), result })
      await page.getByText('Backend result received for the submitted scenario.', { exact: true }).waitFor({ state: 'attached' })
      return result
    }
    const noOverflow = async () => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.goto('http://127.0.0.1:5173')
    await page.getByText('Backend connected', { exact: true }).waitFor()
    await page.getByText('No optimization result yet', { exact: true }).waitFor()
    assert.equal(await page.locator('.metric').count(), 0)
    await page.getByText('Fictional demonstration inputs;', { exact: false }).waitFor()
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 900 })
      await assertChartRendered(page); await noOverflow()
      await page.screenshot({ path: `${output}/initial-${width}.png`, fullPage: true })
    }
    await page.setViewportSize({ width: 1440, height: 900 })
    await nav('Scenario configuration')
    await page.locator('#limit').fill('20')
    await page.locator('#evEnergy').fill('18')
    const result = await run()
    assert.equal(result.feasibility_status, 'feasible')
    const money = n => new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(n)
    assert((await page.locator('.comparison-metrics').innerText()).includes(money(result.optimized_electricity_cost_usd)))
    assert((await page.locator('.energy-context').innerText()).includes(result.optimized_demand_kw.reduce((a,b)=>a+b,0).toFixed(1)))
    const metricsBounds = await page.locator('.comparison-metrics').boundingBox()
    assert(metricsBounds.y + metricsBounds.height < 900, 'Primary metrics in first desktop viewport')
    const chartBounds = await page.locator('.chart').boundingBox()
    assert(chartBounds.y < 800, 'Prominent chart begins in first viewport')
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 900 })
      await assertChartRendered(page); await noOverflow(); await page.evaluate(() => scrollTo(0,0))
      await page.screenshot({ path: `${output}/result-${width}.png`, fullPage: true })
    }
    // Numerical table and chart keyboard navigation remain available.
    await page.locator('.hourly-table summary').click()
    assert.equal(await page.locator('.hourly-table tbody tr').count(), 24)
    await page.locator('.recharts-surface[role="application"]').focus(); await page.keyboard.press('ArrowRight')
    await nav('Energy overview')
    await page.getByText('Feasible — reported by backend').waitFor()
    await nav('Scenario configuration'); await page.locator('#limit').fill('10'); await nav('Energy overview')
    await page.getByText('PREVIOUS SCENARIO · STALE', { exact: true }).waitFor()
    await page.getByText('Submitted scenario & result provenance', { exact: true }).click()
    assert((await page.getByRole('region', { name: 'Submitted snapshot' }).innerText()).includes('20 kW'))
    assert((await page.getByRole('region', { name: 'Editable draft' }).innerText()).includes('10 kW'))
    await page.screenshot({ path: `${output}/stale-mobile.png`, fullPage: true })
    await nav('Scenario configuration'); await page.locator('#limit').fill('20')
    await page.locator('#scheduling-mode').selectOption('joint')
    await nav('Optimization')
    await page.getByText('No optimization result yet', { exact: true }).waitFor()
    const joint = await run(isJointOptimization)
    assert.equal(joint.feasibility_status, 'feasible')
    await nav('AI assistant')
    await page.getByText('AI actions are disabled for joint scheduling', { exact: false }).waitFor()
    await page.locator('#scheduling-mode').selectOption('ev_only')
    await nav('Scenario configuration'); await page.locator('#limit').fill('1')
    const infeasible = await run()
    assert.equal(infeasible.feasibility_status, 'infeasible')
    await page.getByText('This scenario needs more flexibility.', { exact: true }).waitFor()
    assert(await page.locator('.violations li').count() > 0)
    assert.equal(await page.locator('.comparison-metrics').getByText('Unavailable', { exact: true }).count(), 3)
    await page.screenshot({ path: `${output}/infeasible-mobile.png`, fullPage: true })
    // Provider unavailable is injected: no live inference or credential use.
    await nav('AI assistant')
    await page.route('**/api/ai/**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: { message: 'Meta AI is unavailable: injected for browser verification' } }) }))
    await click('Keep peak power demand below 15 kW.'); await click('Review proposed changes')
    await page.getByText('Meta AI is unavailable:', { exact: false }).waitFor()
    await page.screenshot({ path: `${output}/provider-unavailable.png`, fullPage: true })
    await nav('Scenario configuration'); await click('Reset to Default Scenario')
    // Hold a real solver response; test busy guard, then fault recovery.
    let calls = 0
    await page.route(isEvOnlyOptimization, async route => { calls++; const r = await route.fetch(); await new Promise(resolve => setTimeout(resolve, 1500)); await route.fulfill({ response: r }) })
    await click('Run optimization')
    assert(await page.getByRole('button', { name: 'Requesting optimization…' }).isDisabled())
    await page.getByRole('button', { name: 'Run optimization', exact: true }).waitFor()
    assert.equal(calls, 1)
    await page.unroute(isEvOnlyOptimization)
    for (const status of [422, 503, 500]) {
      await page.route(isEvOnlyOptimization, route => route.fulfill({ status, contentType: 'application/json', body: '{}' }))
      await click('Run optimization')
      await page.getByRole('status').filter({ hasText: `HTTP ${status}` }).waitFor()
      await page.unroute(isEvOnlyOptimization)
    }
    await page.route(isEvOnlyOptimization, () => {})
    await click('Run optimization')
    await page.getByRole('status').filter({ hasText: 'timed out after 45 seconds' }).waitFor({ timeout: 50000 })
    await page.unroute(isEvOnlyOptimization)
    await run()
    assert.deepEqual(errors, [])
    await fs.writeFile(`${output}/workspace-results.json`, JSON.stringify({ pass: true, records, errors, checks: 'desktop/tablet/mobile, real EV/joint/infeasible, submitted snapshots, stale, table, keyboard, provider 503 injection, loading, HTTP failures, native timeout and recovery' }, null, 2))
    console.log('PASS: scenario workspace lifecycle, real solver metrics, responsive geometry, provenance, infeasible and failure handling.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
