// Optional QA tool: NODE_PATH=/tmp/gridpilot-browser/node_modules node scripts/browser-qa.cjs
// Install Playwright outside application dependencies and run both dev servers first.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const output = process.env.GRIDPILOT_QA_OUTPUT || '/tmp/gridpilot-phase35-qa'
;(async () => {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const run = () => page.getByRole('button', { name: 'Run optimization', exact: true })
  const nav = label => page.getByRole('navigation').getByRole('button', { name: label, exact: true }).click()
  const noOverflow = async () => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Horizontal page overflow')
  await page.goto('http://127.0.0.1:5173')
  await page.getByText('Backend connected', { exact: true }).waitFor()
  await page.getByText('128.8', { exact: false }).first().waitFor()
  await noOverflow()
  await page.screenshot({ path: `${output}/desktop-overview.png`, fullPage: true })
  await nav('Scenario configuration')
  await page.getByRole('button', { name: 'Reset to Default Scenario' }).click()
  await page.locator('#limit').fill('20')
  await page.locator('#evEnergy').fill('18')
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/optimize') && r.request().method() === 'POST')
  await run().click()
  const response = await responsePromise
  assert.equal(response.status(), 200)
  const result = await response.json()
  assert.equal(result.feasibility_status, 'feasible')
  const submitted = response.request().postDataJSON()
  assert.equal(submitted.building_max_demand_kw, 20)
  assert.equal(submitted.ev_requirements[0].energy_required_kwh, 18)
  assert.equal(result.baseline_demand_kw.length, 24)
  assert.equal(result.optimized_demand_kw.length, 24)
  assert(Math.max(...result.optimized_demand_kw) <= 20 + 1e-6)
  const cost = demand => demand.reduce((sum, kw, h) => sum + kw * submitted.electricity_prices_usd_per_kwh[h], 0)
  assert(Math.abs(cost(result.optimized_demand_kw) - result.optimized_electricity_cost_usd) < 1e-6)
  const comparison = page.locator('.comparison')
  await comparison.getByText('Feasible — reported by backend', { exact: false }).waitFor()
  const money = value => new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(Math.abs(value) < 0.005 ? 0 : value)
  const metrics = comparison.locator('.comparison-metrics > span')
  assert((await metrics.nth(0).innerText()).includes(money(result.baseline_electricity_cost_usd)))
  assert((await metrics.nth(1).innerText()).includes(money(result.optimized_electricity_cost_usd)))
  assert((await metrics.nth(2).innerText()).includes(money(result.baseline_electricity_cost_usd - result.optimized_electricity_cost_usd)))
  await comparison.getByText('Baseline demand', { exact: true }).waitFor()
  await comparison.getByText('Optimized demand', { exact: true }).waitFor()
  await noOverflow()
  await page.screenshot({ path: `${output}/desktop-feasible.png`, fullPage: true })
  await fs.writeFile(`${output}/real-result.json`, JSON.stringify({ submitted, result }, null, 2))
  await nav('Scenario configuration')
  await page.locator('#limit').fill('1')
  const badResponse = page.waitForResponse(r => r.url().endsWith('/api/optimize'))
  await run().click()
  const bad = await (await badResponse).json()
  assert.equal(bad.feasibility_status, 'infeasible')
  assert.equal(bad.optimized_demand_kw, null)
  await comparison.getByText('Infeasible — reported by backend', { exact: false }).waitFor()
  assert.equal(await comparison.locator('.comparison-metrics').getByText('Unavailable', { exact: true }).count(), 3)
  assert(await comparison.locator('.violations li').count() > 0)
  await page.screenshot({ path: `${output}/desktop-infeasible.png`, fullPage: true })
  await nav('Scenario configuration')
  await page.getByRole('button', { name: 'Reset to Default Scenario' }).click()
  // Hold a genuine backend response for six seconds to verify the former 5s boundary.
  let count = 0
  await page.route('**/api/optimize', async route => {
    count++
    const real = await route.fetch()
    await new Promise(resolve => setTimeout(resolve, 6000))
    await route.fulfill({ response: real })
  })
  await run().click()
  await page.getByRole('button', { name: 'Requesting optimization…' }).waitFor()
  assert(await page.getByRole('button', { name: 'Requesting optimization…' }).isDisabled())
  await page.screenshot({ path: `${output}/loading.png`, fullPage: true })
  await page.waitForTimeout(5200)
  assert(await page.getByRole('button', { name: 'Requesting optimization…' }).isDisabled())
  await run().waitFor({ timeout: 10000 })
  assert.equal(count, 1)
  await comparison.getByText('Feasible — reported by backend', { exact: false }).waitFor()
  await page.unroute('**/api/optimize')
  // Fault injection only: successful/infeasible results above came from real GLOP.
  for (const status of [422, 503, 500]) {
    await page.route('**/api/optimize', route => route.fulfill({ status, contentType: 'application/json', body: JSON.stringify({ detail: { code: 'test_failure' } }) }))
    await run().click()
    await page.getByRole('status').filter({ hasText: `HTTP ${status}` }).waitFor()
    assert(await run().isEnabled())
    await page.unroute('**/api/optimize')
  }
  await page.route('**/api/optimize', route => route.abort())
  await run().click()
  await page.getByRole('status').filter({ hasText: 'unavailable or timed out' }).waitFor()
  await page.unroute('**/api/optimize')
  // Exercise the native browser AbortSignal timeout, with no fabricated response.
  await page.route('**/api/optimize', () => {})
  await run().click()
  await page.getByRole('status').filter({ hasText: 'timed out after 45 seconds' }).waitFor({ timeout: 50000 })
  assert(await run().isEnabled())
  await page.screenshot({ path: `${output}/timeout.png`, fullPage: true })
  await page.unroute('**/api/optimize')
  const recoveryResponse = page.waitForResponse(r => r.url().endsWith('/api/optimize') && r.status() === 200)
  await run().click()
  await recoveryResponse
  await page.getByRole('status').filter({ hasText: 'Backend result received' }).waitFor()
  await comparison.getByText('Feasible — reported by backend', { exact: false }).waitFor()
  for (const width of [390, 768, 1024]) {
    await page.setViewportSize({ width, height: 1000 })
    for (const view of ['Energy overview', 'Scenario configuration', 'Optimization', 'AI assistant']) {
      await nav(view)
      await page.waitForTimeout(150)
      await noOverflow()
      if (view === 'Optimization' || view === 'Scenario configuration')
        await page.screenshot({ path: `${output}/${width}-${view.replaceAll(' ', '-')}.png`, fullPage: true })
    }
  }
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ pass: true, genuineResult: result, scenarios: 'real feasible/infeasible, six-second loading, duplicate guard, 422/503/500/network/45-second timeout, desktop and 390/768/1024 layouts', output }, null, 2))
  await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
