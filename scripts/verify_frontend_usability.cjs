// Local non-AI HTTP checks; failures are explicitly injected. No Meta calls.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const AxeBuilder = require(process.env.AXE_MODULE || '@axe-core/playwright').default;
const assert = require('node:assert/strict');
const fs = require('node:fs');
const out = 'artifacts/frontend-usability';
fs.mkdirSync(out, { recursive:true });
const report = { checks:[], accessibility:[], errors:[], requests:[] };
(async () => {
 const browser = await chromium.launch({headless:true, args:['--no-sandbox']});
 const context = await browser.newContext({viewport:{width:1440,height:1000}});
 const page = await context.newPage();
 page.on('pageerror', e => report.errors.push(e.message));
 await context.route('**/api/ai/**', route => { report.requests.push('blocked AI: '+route.request().url()); return route.abort(); });
 context.on('request', r => {if (r.url().includes('/api/optimize')) report.requests.push(r.url());});
 const click = name => page.getByRole('button',{name,exact:true}).click();
 const nav = name => page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name,exact:true}).click();
 const shot = async name => {
   assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), 'horizontal overflow: '+name);
   await page.evaluate(()=>scrollTo(0,0));
   await page.screenshot({path:`${out}/${name}.png`,fullPage:true});
 };
 const audit = async name => {
   const result = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
   report.accessibility.push({name,violations:result.violations.map(v=>({id:v.id,description:v.description,nodes:v.nodes.map(n=>n.target)}))});
 };
 try {
 await page.goto('http://127.0.0.1:5173');
 await page.getByLabel('Business name').fill('First-time Office');
 await page.getByLabel(/Business type/).selectOption('Office');
 await page.getByRole('radio',{name:/Find savings opportunities/}).check();
 await shot('goal-selection-desktop');
 await audit('goal-selection');
 await click('Continue to savings opportunities');
 await page.getByRole('heading',{name:'Add an improvement',exact:true}).waitFor();
 assert.equal(report.requests.length,0);
 assert.equal(await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button').count(),4);
 report.checks.push('Savings-first non-EV onboarding submits no daily solve; four primary sections');
 await click('Load synthetic LED example');
 await click('Calculate savings');
 await page.locator('#savings-results').waitFor();
 await page.locator('[data-financial="energy"]').first().waitFor();
 assert((await page.locator('#savings-results').innerText()).includes('kWh/year'));
 await shot('annual-result-desktop');
 await audit('annual-result');
 // Financial unknowns and signed results use the real annual engine.
 await page.locator('#savings-0-installation_cost_usd').fill('');
 await page.getByLabel('Include a documented customer-specific flat avoidable energy rate').uncheck();
 await click('Calculate savings');
 await page.waitForFunction(()=>document.querySelector('[data-financial="gross"]')?.getAttribute('data-value-state')==='unknown');
 assert.equal(await page.locator('[data-financial="upfront"]').first().getAttribute('data-value-state'),'unknown');
 const financial = page.locator('.savings-financial').first();
 if (!await financial.evaluate(n=>n.open)) await financial.locator(':scope > summary').click();
 await page.getByLabel('Include a documented customer-specific flat avoidable energy rate').check();
 await page.locator('#savings-0-annual_incremental_cost_usd').fill('3000');
 await click('Calculate savings');
 await page.waitForFunction(()=>document.querySelector('[data-financial="net"]')?.getAttribute('data-value-state')==='negative');
 await page.locator('#savings-0-annual_incremental_cost_usd').fill('2500');
 await click('Calculate savings');
 await page.waitForFunction(()=>document.querySelector('[data-financial="net"]')?.textContent.includes('$0.00'));
 report.checks.push('Real annual engine preserves missing rate/cost, negative and zero net savings');
 await nav('Overview');
 assert.equal(await page.getByRole('heading',{name:'Choose your next step'}).count(),1);
 assert.equal(await page.locator('.overview-metrics').count(),0);
 await nav('Savings opportunities');
 // Entered evidence survives section navigation.
 assert.notEqual(await page.locator('#savings-0-old_watts').inputValue(),'');
 await page.setViewportSize({width:390,height:844});
 for (const item of await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button').all()) {
   const box = await item.boundingBox();
   assert(box && box.x >= 0 && box.x + box.width <= 390, 'mobile primary navigation is clipped');
 }
 await shot('annual-result-mobile');
 await audit('savings-mobile');
 await nav('Energy plan');
 await click('Calculate energy plan');
 await page.getByRole('heading',{name:'Your daily energy plan is ready'}).waitFor();
 await shot('daily-overview-mobile');
 await page.getByRole('button',{name:'Table',exact:true}).click();
 assert.equal(await page.locator('.hourly-table[open] tbody tr').count(),24);
 await nav('Energy plan');
 await page.locator('#limit').fill('1');
 await nav('Overview');
 await page.getByRole('heading',{name:'Your inputs have changed'}).waitFor();
 await click('Calculate energy plan');
 await page.getByRole('heading',{name:'Review a capacity issue'}).waitFor();
 report.checks.push('Real daily solve, chart/table, stale inputs, real proven infeasibility');
 await nav('Energy plan');
 await page.locator('#limit').fill('25');
 await page.route('**/api/optimize?**',r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:{code:'solver_unavailable',message:'Controlled service failure'}})}));
 await click('Calculate energy plan');
 assert.equal(await page.locator('#limit').inputValue(),'25');
 await page.unroute('**/api/optimize?**');
 report.checks.push('Injected 503 preserves edited inputs');
 await page.goto('http://127.0.0.1:5173/#configuration');
 await page.locator('#limit').waitFor();
 assert.equal(await page.locator('#limit').inputValue(),'25');
 const saved = await page.evaluate(()=>localStorage.getItem('gridpilot.building-workspace'));
 await page.goto('http://127.0.0.1:5173/#home');
 await click('Preview an example');
 await page.getByRole('heading',{name:'Example snapshot · synthetic building'}).waitFor();
 assert.equal(await page.evaluate(()=>localStorage.getItem('gridpilot.building-workspace')),saved);
 await shot('example-mobile');
 await audit('example');
 report.checks.push('Legacy deep link refresh restores inputs; example opens checked result without replacing saved workspace');
 const before = report.requests.length;
 await page.reload();
 await page.getByRole('heading',{name:'Example snapshot · synthetic building'}).waitFor();
 assert.equal(report.requests.length,before);
 await page.setViewportSize({width:1440,height:1000});
 await shot('example-desktop');
 await nav('Energy plan');
 assert(page.url().endsWith('#example/configuration'));
 await page.reload();
 await page.locator('#limit').waitFor();
 assert.equal(await page.locator('#limit').inputValue(),'25');
 await page.goBack();
 assert(page.url().endsWith('#example'));
 report.checks.push('Example detail hashes preserve refresh and browser history');
 await page.goto('http://127.0.0.1:5173/#comparison');
 await page.getByRole('heading',{name:'Optimization comparison'}).waitFor();
 await nav('My building');
 await page.goBack();
 assert(page.url().endsWith('#comparison'));
 await page.goForward();
 assert(page.url().endsWith('#building'));
 await click('Ask Energy Advisor');
 await page.getByRole('heading',{name:'GridPilot Energy Advisor',exact:true}).waitFor();
 await page.keyboard.press('Tab');
 assert(await page.evaluate(()=>document.activeElement.tagName !== 'BODY'));
 report.checks.push('Browser back/forward and keyboard focus; preview refresh starts no solve or AI request');
 // Independent first-time planning path.
 const p = await context.newPage();
 await p.goto('http://127.0.0.1:5173');
 await p.evaluate(()=>localStorage.clear());
 await p.reload();
 await p.getByLabel('Business name').fill('Planning-first shop');
 await p.getByLabel(/Business type/).selectOption('Retail');
 await p.getByRole('button',{name:'Continue to energy profile',exact:true}).click();
 await p.locator('#setup-analysis-choice').selectOption('flexible');
 await p.getByRole('button',{name:'Continue to your goals',exact:true}).click();
 await p.getByRole('button',{name:'Review workspace',exact:true}).click();
 await p.getByRole('button',{name:'Create workspace and calculate',exact:true}).click();
 await p.getByRole('heading',{name:'Your daily energy plan is ready'}).waitFor();
 report.checks.push('Planning-first flexible equipment without EVs completes a real daily solve');
 // A controlled offline service cannot prevent loading the saved example.
 await page.route('**/api/**', r=>r.abort());
 await page.goto('http://127.0.0.1:5173/#example');
 await page.getByRole('heading',{name:'Your daily energy plan is ready'}).waitFor();
 assert.equal(await page.locator('.overview-metrics').count(),1);
 await click('Calculate energy plan');
 await page.getByRole('heading',{name:'Your energy plan needs attention'}).waitFor();
 assert.equal(await page.locator('.overview-metrics').count(),0);
 report.checks.push('Controlled offline preview remains usable; failed explicit calculation clears snapshot rather than substituting it');
 assert.equal(report.requests.filter(x=>x.startsWith('blocked AI')).length,0);
 assert.deepEqual(report.errors,[]);
 } finally { fs.writeFileSync(`${out}/verification.json`,JSON.stringify(report,null,2)); await browser.close(); }
 console.log(JSON.stringify(report,null,2));
})().catch(e=>{console.error(e);process.exitCode=1});
